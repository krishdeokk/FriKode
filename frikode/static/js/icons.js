/**
 * Returns a language/extension specific color and icon.
 */
export function getFileIcon(filename) {
  const ext = filename.split(".").pop().toLowerCase();
  switch (ext) {
    case "py":
      return { icon: Icons.fileCode, color: "#38bdf8", lang: "Python" };
    case "js":
    case "mjs":
    case "cjs":
      return { icon: Icons.fileCode, color: "#facc15", lang: "JavaScript" };
    case "ts":
      return { icon: Icons.fileCode, color: "#60a5fa", lang: "TypeScript" };
    case "html":
    case "htm":
      return { icon: Icons.fileCode, color: "#fb923c", lang: "HTML" };
    case "css":
    case "scss":
      return { icon: Icons.fileCode, color: "#38bdf8", lang: "CSS" };
    case "json":
      return { icon: Icons.fileCode, color: "#4ade80", lang: "JSON" };
    case "md":
      return { icon: Icons.file, color: "#c084fc", lang: "Markdown" };
    case "rs":
      return { icon: Icons.fileCode, color: "#f87171", lang: "Rust" };
    case "c":
    case "cpp":
    case "h":
      return { icon: Icons.fileCode, color: "#818cf8", lang: "C/C++" };
    default:
      return { icon: Icons.file, color: "#94a3b8", lang: "Text" };
  }
}

